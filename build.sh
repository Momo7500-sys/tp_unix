#!/bin/sh

# Проверяем, передан ли исходный файл в качестве аргумента
if [ -z "$1" ]; then
    echo "Ошибка: Не указан исходный файл." >&2
    echo "Использование: $0 <исходный_файл>" >&2
    exit 2
fi

SRC_FILE="$1"

# Проверяем существование и доступность файла на чтение
if [ ! -r "$SRC_FILE" ]; then
    echo "Ошибка: Файл '$SRC_FILE' не найден или недоступен для чтения." >&2
    exit 3
fi

# Получаем абсолютный путь и директорию исходного файла
SRC_DIR=$(dirname "$SRC_FILE")
SRC_BASE=$(basename "$SRC_FILE")

# 1. Анализируем текст файла и ищем комментарий вида "Output: имя_файла"
# Используем sed для поиска строки с 'Output:' и извлечения имени файла
OUT_NAME=$(sed -n -e 's/.*Output:[[:space:]]*\([^[:space:]]*\).*/\1/p' "$SRC_FILE")

if [ -z "$OUT_NAME" ]; then
    echo "Ошибка: В файле не найден комментарий с ключевым словом 'Output:'." >&2
    exit 4
fi

# 2. Создаем временный каталог с помощью mktemp
TMP_DIR=$(mktemp -d)
if [ ! -d "$TMP_DIR" ]; then
    echo "Ошибка: Не удалось создать временный каталог." >&2
    exit 5
fi

# 3. Функция автоматической очистки временного каталога при любых исходах
clean_up() {
    rc=$? # Запоминаем код возврата последней выполненной команды
    trap - EXIT HUP INT QUIT TERM # Сбрасываем trap во избежание рекурсии
    if [ -d "$TMP_DIR" ]; then
        rm -rf "$TMP_DIR" # Удаляем временный каталог со всеми промежуточными файлами
    fi
    exit $rc
}

# Регистрируем обработчик сигналов (включая аварийное завершение)
trap clean_up EXIT HUP INT QUIT TERM

# Копируем исходный файл во временный каталог, чтобы сборка происходила там
cp "$SRC_FILE" "$TMP_DIR/$SRC_BASE"
cd "$TMP_DIR" || exit 6

# 4. Определение типа файла и сборка
case "$SRC_BASE" in
    *.c)
        # Компиляция программы на C
        gcc -O2 "$SRC_BASE" -o "$OUT_NAME"
        ;;
    *.cpp|*.cc|*.cxx)
        # Компиляция программы на C++
        g++ -O2 "$SRC_BASE" -o "$OUT_NAME"
        ;;
    *.tex)
        # Сборка документа TeX (pdfLaTeX)
        pdflatex -interaction=nonstopmode "$SRC_BASE"
        ;;
    *)
        echo "Ошибка: Поддерживаются только файлы .c, .cpp и .tex" >&2
        exit 7
        ;;
esac

# Проверяем, успешно ли прошла компиляция/сборка
if [ $? -ne 0 ]; then
    echo "Ошибка: Сборка файла завершилась неудачно." >&2
    exit 1 # Возвращаем информативный код ошибки
fi

# 5. Переносим конечный файл обратно в каталог к исходному файлу
if [ -f "$OUT_NAME" ]; then
    cp "$OUT_NAME" "$SRC_DIR/$OUT_NAME"
else
    echo "Ошибка: Конечный файл '$OUT_NAME' не был создан в процессе сборки." >&2
    exit 8
fi

echo "Сборка успешно завершена! Файл сохранен как: $SRC_DIR/$OUT_NAME"
# Здесь автоматически сработает trap (clean_up) и удалит TMP_DIR
